#!/usr/bin/env python3
"""Compile shaders/blit.hlsl to DXIL and emit src/dt_blit_blobs.cpp.

The present blit is the only shader in this port that is not the guest's, so it
is the only one that needs a host compiler. dxc is already on this machine --
XenosRecomp vendors it, and gen_shader_blobs.py already drives it the same way.

Run from anywhere:  python scripts/gen_blit_blobs.py
Committed output:   src/dt_blit_blobs.cpp  (so a normal build needs no dxc)
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HLSL = os.path.join(REPO, "shaders", "blit.hlsl")
OUT = os.path.join(REPO, "src", "dt_blit_blobs.cpp")

# Same dxc gen_shader_blobs.py uses. Not vendored into this repo: it is a build
# tool, not a build input, and the compiled output below is committed.
DXC_CANDIDATES = [
    os.path.join(REPO, "..", "_tools", "XenosRecomp", "thirdparty", "dxc-bin", "bin", "x64", "dxc.exe"),
    os.path.join(REPO, "..", "_tools", "XenosRecomp-main", "thirdparty", "dxc-bin", "bin", "x64", "dxc.exe"),
]


def find_dxc() -> str:
    for c in DXC_CANDIDATES:
        if os.path.exists(c):
            return os.path.abspath(c)
    sys.exit("dxc.exe not found. Looked in:\n  " + "\n  ".join(os.path.abspath(c) for c in DXC_CANDIDATES))


def compile_one(dxc: str, profile: str, entry: str) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, entry + ".dxil")
        r = subprocess.run(
            [dxc, "-T", profile, "-E", entry, "-HV", "2021", "-all-resources-bound", "-Fo", obj, HLSL],
            capture_output=True, text=True)
        if r.returncode != 0 or not os.path.exists(obj):
            sys.exit("dxc FAILED for %s (%s)\n%s%s" % (entry, profile, r.stdout[-2000:], r.stderr[-2000:]))
        blob = open(obj, "rb").read()
    # DXIL containers start with 'DXBC' -- the container format did not get a new
    # magic when the bytecode inside it changed. A blob without it is not signed
    # and D3D12 will refuse the pipeline at creation with no useful message.
    if blob[:4] != b"DXBC":
        sys.exit("%s: output is not a DXIL container (magic %r) -- is dxil.dll beside dxc.exe?" % (entry, blob[:4]))
    return blob


def emit(name: str, blob: bytes) -> str:
    body = []
    for i in range(0, len(blob), 16):
        body.append("    " + " ".join("0x%02X," % b for b in blob[i:i + 16]))
    return "const unsigned char %s[] = {\n%s\n};\nconst size_t %s_size = sizeof(%s);\n" % (
        name, "\n".join(body), name, name)


def main() -> int:
    dxc = find_dxc()
    vs = compile_one(dxc, "vs_6_0", "main_vs")
    ps = compile_one(dxc, "ps_6_0", "main_ps")

    with open(OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("// GENERATED by scripts/gen_blit_blobs.py from shaders/blit.hlsl -- do not hand-edit.\n")
        f.write("//\n")
        f.write("// Committed so a normal build needs no dxc. Regenerate after editing the HLSL.\n")
        f.write("#include \"dt_blit_blobs.h\"\n\nnamespace dt_blit_blobs {\n\n")
        f.write(emit("kBlitVs", vs))
        f.write("\n")
        f.write(emit("kBlitPs", ps))
        f.write("\n}  // namespace dt_blit_blobs\n")

    print("wrote %s  (vs %d bytes, ps %d bytes)" % (OUT, len(vs), len(ps)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
