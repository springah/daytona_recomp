#!/usr/bin/env python3
"""Compile shaders/imgui.hlsl to DXIL + SPIR-V and emit src/dt_imgui_blobs.cpp.

Same recipe as gen_blit_blobs.py (the present blit); see the notes there. This
pair draws the SDK's ImGui overlay (settings / console / hints) in the native
renderer's detached-overlay pass.

Run from anywhere:  python scripts/gen_imgui_blobs.py
Committed output:   src/dt_imgui_blobs.cpp  (so a normal build needs no dxc)
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HLSL = os.path.join(REPO, "shaders", "imgui.hlsl")
OUT = os.path.join(REPO, "src", "dt_imgui_blobs.cpp")

DXC_CANDIDATES = [
    os.path.join(REPO, "..", "_tools", "XenosRecomp", "thirdparty", "dxc-bin", "bin", "x64", "dxc.exe"),
    os.path.join(REPO, "..", "_tools", "XenosRecomp-main", "thirdparty", "dxc-bin", "bin", "x64", "dxc.exe"),
]


def find_dxc() -> str:
    for c in DXC_CANDIDATES:
        if os.path.exists(c):
            return os.path.abspath(c)
    sys.exit("dxc.exe not found. Looked in:\n  " + "\n  ".join(os.path.abspath(c) for c in DXC_CANDIDATES))


def compile_one(dxc: str, profile: str, entry: str, spirv: bool = False) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, entry + (".spv" if spirv else ".dxil"))
        cmd = [dxc, "-T", profile, "-E", entry, "-HV", "2021", "-all-resources-bound"]
        if spirv:
            # space<N> -> set N, register <M> -> binding M (dxc's default; the
            # pipeline layout is built to match: texture set 0, sampler set 1,
            # push constants for the transform).
            cmd += ["-spirv", "-fvk-t-shift", "0", "0", "-fvk-s-shift", "0", "1"]
        cmd += ["-Fo", obj, HLSL]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0 or not os.path.exists(obj):
            sys.exit("dxc FAILED for %s (%s%s)\n%s%s" % (
                entry, profile, ", spirv" if spirv else "", r.stdout[-2000:], r.stderr[-2000:]))
        blob = open(obj, "rb").read()
    if spirv:
        if blob[:4] != b"\x03\x02\x23\x07":
            sys.exit("%s: output is not SPIR-V (magic %r)" % (entry, blob[:4]))
    elif blob[:4] != b"DXBC":
        sys.exit("%s: output is not a DXIL container (magic %r) -- is dxil.dll beside dxc.exe?" % (entry, blob[:4]))
    return blob


def emit(name: str, blob: bytes) -> str:
    body = []
    for i in range(0, len(blob), 16):
        body.append("    " + " ".join("0x%02X," % b for b in blob[i:i + 16]))
    return "const unsigned char %s[] = {\n%s\n};\nconst size_t %s_size = sizeof(%s);\n" % (
        name, "\n".join(body), name, name)


def main() -> int:
    dxc = find_dxc()
    vs = compile_one(dxc, "vs_6_0", "main_vs")
    ps = compile_one(dxc, "ps_6_0", "main_ps")
    vs_spv = compile_one(dxc, "vs_6_0", "main_vs", spirv=True)
    ps_spv = compile_one(dxc, "ps_6_0", "main_ps", spirv=True)

    with open(OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("// GENERATED by scripts/gen_imgui_blobs.py from shaders/imgui.hlsl -- do not hand-edit.\n")
        f.write("//\n")
        f.write("// Committed so a normal build needs no dxc. Regenerate after editing the HLSL.\n")
        f.write("#include \"dt_imgui_blobs.h\"\n\nnamespace dt_imgui_blobs {\n\n")
        f.write(emit("kImGuiVs", vs))
        f.write("\n")
        f.write(emit("kImGuiPs", ps))
        f.write("\n")
        f.write(emit("kImGuiVsSpirv", vs_spv))
        f.write("\n")
        f.write(emit("kImGuiPsSpirv", ps_spv))
        f.write("\n}  // namespace dt_imgui_blobs\n")

    print("wrote %s\n  DXIL   vs %d  ps %d\n  SPIR-V vs %d  ps %d" % (
        OUT, len(vs), len(ps), len(vs_spv), len(ps_spv)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
